/**
 * A receiver: a reducer another database calls through an outbox. It is always
 * client-callable (the host delivers inter-database calls only to public
 * reducers), and its wire name is pinned to `snakeCaseName(key)` whatever the
 * module's case policy, because the caller's binding names it by that string.
 */
export type ReceiverSpec<
  Params extends StructLikeValueType = StructLikeValueType,
  Errors extends AnyErrorDefinition | undefined =
    | AnyErrorDefinition
    | undefined,
> = ReducerSpec<Params, Errors, true> & {
  readonly receiver: true
}

export const isReceiverSpec = (spec: unknown): boolean =>
  typeof spec === "object" &&
  spec !== null &&
  (spec as { readonly receiver?: unknown }).receiver === true

/**
 * Parameter names an outbox row reserves for its own bookkeeping. A receiver
 * parameter with one of these names could not be told apart from the outbox
 * metadata column of the same name.
 */
export const receiverReservedParamNames: ReadonlySet<string> = new Set([
  "msgId",
  "target",
  "enqueuedAt",
])

/**
 * The shape of one reducer in a receiver binding generated by native
 * `spacetime generate --bindings module`. Kept structural so the public
 * declaration surface never names the host-only SDK entrypoint's types.
 */
export type RemoteReducerBinding = {
  readonly name: string
  readonly signatureHash: bigint
  readonly params: Readonly<Record<string, unknown>>
}

/** The default export of a generated receiver binding (`remoteModule(...)`). */
export type RemoteModuleBinding = {
  readonly reducers: Readonly<Record<string, RemoteReducerBinding>>
  readonly identity: () => unknown
}

type InterfaceGroupLike = {
  readonly kind: "stdbGroup"
  readonly id: string
  readonly endpoints: ReadonlyArray<{
    readonly declKind: string
    readonly name: string
    readonly spec: unknown
  }>
}

type ReceiversOfGroup<Group> = Group extends {
  readonly [GroupReducersTypeId]: infer Reducers extends Record<
    string,
    ReducerSpec
  >
}
  ? Reducers
  : never

/**
 * A group of receivers one database exposes to its peers. Both sides import it:
 * the receiving module implements `group`, the sending module declares outboxes
 * against it.
 *
 * It carries no binding. A generated binding imports the server SDK, which
 * loads only inside a SpacetimeDB host, and a contract is also imported by
 * workers, browsers and CLIs; the sending module's entry pairs the interface
 * with its binding instead (`bind`), and hands that to `build`.
 */
export type RemoteInterface<
  Name extends string = string,
  Receivers extends Record<string, ReducerSpec> = Record<string, ReducerSpec>,
> = {
  readonly kind: "remoteInterface"
  readonly name: Name
  readonly groupId: string
  readonly receivers: Receivers
}

export type AnyRemoteInterface = RemoteInterface<
  string,
  Record<string, ReducerSpec>
>

/**
 * The interface `make({ name, group })` returns, by name. A package that
 * emits declarations annotates an exported interface with it: the inferred
 * receiver record is built from the library's internal type helpers, which a
 * consumer's declaration emit cannot name (TS2883). Exported from the package
 * root by this name so that emit can name it.
 */
export type RemoteInterfaceOf<Name extends string, Group> = RemoteInterface<
  Name,
  ReceiversOfGroup<Group>
>

export type ReceiverKeysOf<Interface extends AnyRemoteInterface> =
  keyof Interface["receivers"] & string

/**
 * A remote interface paired with the binding native codegen generated for it.
 * Host-only: only a module entry makes one, next to the binding's import, and
 * passes it to `build` as one of its `receiverBindings`.
 */
export type RemoteInterfaceBinding<
  Interface extends AnyRemoteInterface = AnyRemoteInterface,
> = {
  readonly kind: "remoteInterfaceBinding"
  readonly interface: Interface
  /**
   * Kept structural: a generated binding's own type names SDK internals and
   * its module's `unique symbol`, which no declaration file can name.
   */
  readonly binding: RemoteModuleBinding
}

export type AnyRemoteInterfaceBinding =
  RemoteInterfaceBinding<AnyRemoteInterface>

declare const PeerIdentityTypeId: unique symbol

/**
 * A database identity this module may call through `Interface`. Only a peer
 * resolver mints one (`RemoteInterface.peer`), from a registry row or an
 * environment value; it is never taken from a call argument. The brand is
 * compile-time only.
 */
export type PeerIdentity<Interface extends { readonly name: string }> =
  Identity & {
    readonly [PeerIdentityTypeId]: Interface["name"]
  }

type BindingCoversReceivers<Receivers, Binding> = [
  Exclude<keyof Receivers, BindingReceiverKeysOf<Binding>>,
] extends [never]
  ? unknown
  : {
      readonly [Key in Exclude<
        keyof Receivers,
        BindingReceiverKeysOf<Binding>
      > &
        string as `Receiver binding is missing receiver ${Key}; regenerate it`]: never
    }

type BindingReducersOf<Binding> = Binding extends {
  readonly reducers: infer Reducers
}
  ? Reducers
  : never

/**
 * The receiver keys a binding's declaration names. A generated declaration
 * intersects `RemoteModuleBinding`, whose `reducers` is a string record, so a
 * plain `keyof` is `string` and would cover every receiver; only the declared
 * keys count.
 */
type BindingReceiverKeysOf<Binding> = keyof {
  readonly [Key in keyof BindingReducersOf<Binding> as string extends Key
    ? never
    : Key]: unknown
}

const invalid = (
  code: "InvalidRemoteInterface" | "RemoteInterfaceBindingMismatch",
  path: ReadonlyArray<string | number>,
  message: string,
) => makeStdbDiagnostic(code, path, message)

const sameKeys = (
  left: ReadonlyArray<string>,
  right: ReadonlyArray<string>,
): boolean =>
  left.length === right.length &&
  left.every((key, index) => key === right[index])

/**
 * Names a group of receivers as an interface other databases call.
 *
 * Every endpoint of the group must be a receiver, and `name` must be a
 * SpacetimeDB identifier: native codegen namespaces the binding's type names
 * with it. The binding is paired later, in the sending module's entry (`bind`).
 */
export const make = <
  const Name extends string,
  const Group extends InterfaceGroupLike,
>(options: {
  readonly name: Name
  readonly group: Group
}): RemoteInterface<Name, ReceiversOfGroup<Group>> => {
  const diagnostics = []
  if (!isSpaceTimeDbAsciiIdentifier(options.name)) {
    diagnostics.push(
      invalid(
        "InvalidRemoteInterface",
        ["remoteInterfaces", options.name],
        `Remote interface name ${options.name} must be a SpaceTimeDB identifier; it namespaces the binding's type names.`,
      ),
    )
  }

  const receivers: Record<string, ReducerSpec> = {}
  for (const endpoint of options.group.endpoints) {
    if (endpoint.declKind !== "reducer" || !isReceiverSpec(endpoint.spec)) {
      diagnostics.push(
        invalid(
          "InvalidRemoteInterface",
          ["remoteInterfaces", options.name, endpoint.name],
          `Remote interface ${options.name} group ${options.group.id} endpoint ${endpoint.name} must be declared with StdbFn.receiver(...).`,
        ),
      )
      continue
    }
    receivers[endpoint.name] = endpoint.spec as ReducerSpec
  }

  if (diagnostics.length > 0) {
    throw new StdbValidationError({ diagnostics })
  }

  return {
    kind: "remoteInterface",
    name: options.name,
    groupId: options.group.id,
    receivers: receivers as ReceiversOfGroup<Group>,
  }
}

/**
 * Pairs an interface with the binding native codegen generated for it, for
 * `build`'s `receiverBindings`. Call it only in a module entry: the binding's
 * module loads only inside a SpacetimeDB host.
 *
 * The binding must carry each receiver under its contract key, with the pinned
 * wire name and the parameters in declaration order. A binding that fails this
 * was generated from another version of the group: regenerate it rather than
 * editing it.
 */
export const bind = <
  const Interface extends AnyRemoteInterface,
  const Binding extends RemoteModuleBinding,
>(
  remoteInterface: Interface,
  binding: Binding & BindingCoversReceivers<Interface["receivers"], Binding>,
): RemoteInterfaceBinding<Interface> => {
  const receivers: Readonly<Record<string, ReducerSpec>> =
    remoteInterface.receivers
  const diagnostics = []
  for (const [key, spec] of Object.entries(receivers)) {
    const path = ["remoteInterfaces", remoteInterface.name, key]
    const bound = binding.reducers[key]
    if (bound === undefined) {
      diagnostics.push(
        invalid(
          "RemoteInterfaceBindingMismatch",
          path,
          `The binding of remote interface ${remoteInterface.name} has no receiver ${key}; regenerate it.`,
        ),
      )
      continue
    }

    const wireName = snakeCaseName(key)
    if (bound.name !== wireName) {
      diagnostics.push(
        invalid(
          "RemoteInterfaceBindingMismatch",
          [...path, "name"],
          `The binding of remote interface ${remoteInterface.name} calls ${key} as ${bound.name}, not ${wireName}; regenerate it.`,
        ),
      )
    }

    const declaredParams = Object.keys(structFields(spec.params) ?? {})
    const boundParams = Object.keys(bound.params)
    if (!sameKeys(declaredParams, boundParams)) {
      diagnostics.push(
        invalid(
          "RemoteInterfaceBindingMismatch",
          [...path, "params"],
          `The binding of remote interface ${remoteInterface.name} gives ${key} params (${boundParams.join(", ")}), not (${declaredParams.join(", ")}); regenerate it.`,
        ),
      )
    }
  }

  if (diagnostics.length > 0) {
    throw new StdbValidationError({ diagnostics })
  }

  return { kind: "remoteInterfaceBinding", interface: remoteInterface, binding }
}

/**
 * Brands `identity` as a peer reachable through `remoteInterface`. Call it only
 * from the module's peer resolver, after reading the identity from a registry
 * row or a declared environment value.
 */
export const peer = <Interface extends AnyRemoteInterface>(
  _remoteInterface: Interface,
  identity: Identity,
): PeerIdentity<Interface> =>
  // Brand seam: the brand is compile-time only, so the value is the identity.
  identity as PeerIdentity<Interface>
